/**
 * Chain event decode surface: HookReady topic/decoder and the SignalSubmitted
 * order-id decoder are owned by @uvp-eth/protocol-bindings; this module only
 * re-exports them for the core entry and decodes the generated order id from a
 * trigger transaction receipt.
 */
import { decodeEventLog, type Hex } from 'viem';
import {
  SIGNAL_SUBMITTED_ABI,
  SIGNAL_SUBMITTED_TOPIC,
  normalizeBytes32,
} from '@uvp-eth/protocol-bindings';
import type { StateMachineRawLog } from '@uvp-eth/protocol-bindings';

export {
  HOOK_READY_TOPIC,
  decodeHookReadyLog,
  hookReadyEventId,
  tryHookReadyEventId,
  tryNormalizeStateMachineAddress,
} from '@uvp-eth/protocol-bindings';

export type {
  StateMachineArtifactIndex,
  StateMachineHookMetadata,
  StateMachineHookReady,
  StateMachineRawLog,
  StateMachineSignalMetadata,
} from '@uvp-eth/protocol-bindings';

/** Order id generated by the state machine for an orderId=0 trigger submission. */
export function triggeredOrderIdFromLogs(logs: readonly StateMachineRawLog[]): Hex | undefined {
  for (const log of logs) {
    if (log.topics[0] !== SIGNAL_SUBMITTED_TOPIC) {
      continue;
    }
    const decoded = decodeEventLog({
      abi: SIGNAL_SUBMITTED_ABI,
      eventName: 'SignalSubmitted',
      data: log.data,
      topics: [...log.topics] as [Hex, ...Hex[]],
    });
    const orderId = (decoded.args as { readonly orderId?: unknown }).orderId;
    if (typeof orderId !== 'string') {
      throw new Error('SignalSubmitted log did not decode an orderId');
    }
    return normalizeBytes32(orderId, 'SignalSubmitted.orderId');
  }
  return undefined;
}
